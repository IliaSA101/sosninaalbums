import type { SegItem } from '../../base/tpl/Seg.svelte'

// Подрезка, чтобы закрыть лист (104): предел подрезки по стороне, %. Раскладку растягивает Go,
// здесь только перевод поля настроек в положение переключателя и тексты (образец — fold.ts).
export type CropPct = 0 | 5 | 10 | 15

export const CROP_ITEMS: readonly SegItem<CropPct>[] = [
  { id: 0, label: 'Нет', title: 'Фото целиком' },
  { id: 5, label: 'до 5 %', title: 'Подрезать не больше 5 % по стороне' },
  { id: 10, label: 'до 10 %', title: 'Подрезать не больше 10 % по стороне' },
  { id: 15, label: 'до 15 %', title: 'Подрезать не больше 15 % по стороне' },
]

// Нет поля или чужое число — «Нет»: Go зажимает к шагам сам, дроби на фронте не сравниваются.
export function cropOf(s: { crop?: number }): CropPct {
  const c = CROP_ITEMS.find((i) => i.id === s.crop)
  return c ? c.id : 0
}

export function cropNote(c: CropPct): string {
  if (c === 0) return 'Фото стоят целиком: если пропорции раскладки не совпали с листом, у полей остаются белые полосы.'
  return `Если раскладке до полей листа не хватает немного, фото обрежутся по краям — не больше ${c} % по стороне, по центру кадра. Свой кадр фото не подрезается.`
}

// Вторая строка: пока выбрано не то, что в альбоме. Ручные развороты подрезка не трогает.
export function cropChangeNote(applied: CropPct, picked: CropPct): string {
  if (applied === picked) return ''
  if (picked === 0) return 'После «Применить» фото снова встанут целиком, у полей вернутся белые полосы.'
  return 'После «Применить» раскладки останутся теми же; где хватит подрезки, фото закроют лист. Ручные развороты не меняются.'
}
