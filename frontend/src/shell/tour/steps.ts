// литералом в разметке (страж steps.test.ts). Тексты идут через articleText: метки клавиш и куски по уровню (как в статьях справочника).
import type { FeatureId } from '../../base/prefs/levels'
import type { SpotKey } from '../guide/articles'

export type TourId = 'folders' | 'library' | 'autobuild' | 'timeline' | 'layouts' | 'photo' | 'export'

export interface TourStep {
  id: TourId
  title: string // ≤ 32 знаков
  feature: FeatureId // нет на уровне («Свой») — шаг пропускается
  article: string // статья справочника: «Подробнее в справочнике»
  ready: string // место живое (≤ 200 знаков после articleText)
  empty: string // места или состояния нет
  spot: SpotKey // место, когда живое
  emptySpot?: SpotKey // место, когда нет (обычно холст); без него — spot
  avoid?: readonly string[] // CSS-селекторы областей, которые карточка не закрывает (122)
}

