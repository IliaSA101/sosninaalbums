package model

import (
	"fmt"
	"math"
)

// bleedSlack — запас поля над обрезом, мм: поле меньше обреза + 2 мм кладёт край фото к линии
// реза, а сдвиг ножа даёт белую нить (0.23-q7 (а)).
const bleedSlack = 2.0

// MarginNote — предупреждение для «Поля» и «Обрез» в настройках альбома. Обрез только рисуется,
// фото в него не выводятся: при 0 < поле < обрез + 2 мм край фото у линии реза. Пусто, если поле 0
// (фото уходят в обрез), поле от обреза + 2 мм или обреза нет. Принимает значения формы, а не
// сохранённые: интерфейс зовёт до «Применить». Числа сравниваются по 0,01 мм — шаг формы 0,5 мм,
// а сумма вроде 0,3 + 2 в двоичной дроби неточна.
func MarginNote(margin, bleed float64) string {
	m, b := cmm(margin), cmm(bleed)
	if b <= 0 || m <= 0 || m >= b+cmm(bleedSlack) {
		return ""
	}
	return fmt.Sprintf("Край фото у линии реза: при сдвиге ножа — белая нить. Поставьте 0 или от %s мм", MmText(bleed+bleedSlack))
}

// cmm — мм в сотых; NaN и Inf дают 0, то есть «нет предупреждения».
func cmm(v float64) float64 {
	if math.IsNaN(v) || math.IsInf(v, 0) {
		return 0
	}
	return math.Round(v * 100)
}
