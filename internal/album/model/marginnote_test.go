package model

import (
	"math"
	"testing"
)

func TestMarginNoteBleed(t *testing.T) {
	const warn = "Край фото у линии реза: при сдвиге ножа — белая нить. Поставьте 0 или от "
	cases := []struct {
		name          string
		margin, bleed float64
		want          string // "" — без предупреждения; иначе N в тексте
	}{
		{"поля 0 — фото в обрез", 0, 3, ""},
		{"ровно обрез+2", 5, 3, ""},
		{"выше обреза+2", 12, 3, ""},
		{"чуть меньше обреза+2", 4.9, 3, "5"},
		{"поля равны обрезу (случай владельца 3/3)", 3, 3, "5"},
		{"обрез 0", 3, 0, ""},
		{"обрез 0, поля 0", 0, 0, ""},
		{"малые поля", 0.5, 3, "5"},
		{"дробные мм: ровно", 3.1, 1.1, ""},
		{"дробные мм: чуть меньше", 3, 1.1, "3,1"},
		{"дробные мм: 0,3+2 неточна в двоичной дроби", 2.3, 0.3, ""},
		{"обрез 2,5", 4, 2.5, "4,5"},
		{"предел обреза 10", 11.5, 10, "12"},
		{"отрицательные", -1, 3, ""},
		{"NaN", math.NaN(), 3, ""},
		{"Inf в обрезе", 3, math.Inf(1), ""},
	}
	for _, c := range cases {
		got := MarginNote(c.margin, c.bleed)
		want := ""
		if c.want != "" {
			want = warn + c.want + " мм"
		}
		if got != want {
			t.Errorf("%s: MarginNote(%v, %v) = %q, ждали %q", c.name, c.margin, c.bleed, got, want)
		}
	}
}
