// cyrLatin — кириллические буквы, нарисованные как латинские.
var cyrLatin = map[rune]rune{'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X'}

var glyphs = buildGlyphs()

const (
	glyphW   = 5
	glyphH   = 7
	glyphAdv = 6 // шаг буквы без масштаба
	lineAdv  = 9 // шаг строки без масштаба
)

func buildGlyphs() map[rune][glyphH]uint8 {
	out := make(map[rune][glyphH]uint8, len(glyphSrc))
	for r, src := range glyphSrc {
		var g [glyphH]uint8
		for y, row := range strings.Fields(src) {
			for x, c := range row {
				if c == '1' {
					g[y] |= 1 << (glyphW - 1 - x)
				}
			}
		}
		out[r] = g
	}
	return out
}

// glyphOf — буква шрифта для r: заглавная, кириллица-двойник латинской, иначе «?».
func glyphOf(r rune) [glyphH]uint8 {
	r = unicode.ToUpper(r)
	if l, ok := cyrLatin[r]; ok {
		r = l
	}
	if g, ok := glyphs[r]; ok {
		return g
	}
	return glyphs['?']
}

// drawText рисует s с левым верхним углом в (x, y), масштаб sc (клетка — sc×sc px).
func drawText(dst *image.NRGBA, x, y int, s string, sc int, c color.NRGBA) {
	b := dst.Bounds()
	for i, r := range []rune(s) {
		g := glyphOf(r)
		for gy := range glyphH {
			for gx := range glyphW {
				if g[gy]&(1<<(glyphW-1-gx)) == 0 {
					continue
				}
				for dy := range sc {
					for dx := range sc {
						px, py := x+i*glyphAdv*sc+gx*sc+dx, y+gy*sc+dy
						if px >= b.Min.X && px < b.Max.X && py >= b.Min.Y && py < b.Max.Y {
							dst.SetNRGBA(px, py, c)
						}
					}
				}
			}
		}
	}
}

// wrapText режет s по словам на строки не шире width клеток; последняя строка при нехватке места
// заканчивается «…» (многоточие — три точки). maxLines — не больше строк.
func wrapText(s string, width, maxLines int) []string {
	var lines []string
	cur := ""
	for _, w := range strings.Fields(s) {
		for len([]rune(w)) > width { // слово длиннее строки — по знакам
			if cur != "" {
				lines = append(lines, cur)
				cur = ""
			}
			rs := []rune(w)
			lines = append(lines, string(rs[:width]))
			w = string(rs[width:])
		}
		switch {
		case cur == "":
			cur = w
		case len([]rune(cur))+1+len([]rune(w)) <= width:
			cur += " " + w
		default:
			lines = append(lines, cur)
			cur = w
		}
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	if len(lines) > maxLines {
		lines = lines[:maxLines]
		last := []rune(lines[maxLines-1])
		if len(last) > width-3 {
			last = last[:width-3]
		}
		lines[maxLines-1] = string(last) + "..."
	}
	return lines
}
