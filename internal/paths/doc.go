// Package paths — граница безопасности путей: пути из файла проекта, настроек и
// вызовов интерфейса (фон, проводник, перепривязка, последние папки и альбомы)
// проходят CheckLocalPath, прежде чем их откроют, прочитают или покажут в проводнике.
//
// CheckLocalPath отклоняет UNC и сетевые шары, пространства имён устройств
// (`\\?\`, `\\.\`, `\??\`), пути без буквы диска или с текущей папкой (`\x`,
// `C:x`), альтернативные потоки NTFS (двоеточие дальше второй позиции), NUL и
// пути длиннее MaxPathLen. Разрешённый вид на Windows — только `X:\…` / `X:/…`;
// на остальных ОС — абсолютный путь без `//`.
//
// Пакет не зависит от остальных пакетов проекта. Вызывают: app (фон-файл,
// проводник, перепривязка, OpenRecent), prefs (последние папки и альбомы),
// album (AddFolder, Load в salbum, перепривязка отметок), library (SplitPath). Остальное —
// помощники перепривязки (PrefixMap, ReplacePrefix, DriveLetter, SwapDrive),
// сравнение путей (SamePath), NoPath (ошибка для лога без путей) и LogQ (строка из
// файла для лога: в кавычках, не длиннее 40 знаков). Помощники
// перепривязки сами отсекают нелокальный результат (ok = false), SamePath держит
// ту же семантику томов и регистра.
//
// Вне границы, по замыслу: файл альбома из диалога, Open/LastProject и drag-n-drop
// (OnFileDrop: os.Stat до AddFolder) — альбом может лежать на сетевом диске, это
// выбор самого пользователя.
//
// Относительные пути внутри файла проекта (checkRel, relPath) сюда не входят:
// их ошибка — «файл проекта повреждён», это смысл формата, и они остаются в album/salbum.
