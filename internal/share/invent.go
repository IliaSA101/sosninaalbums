// Invent — пароль для клиента «слово-NNNN»: слово из списка и четыре цифры, оба из crypto/rand.
func Invent() (string, error) { return inventFrom(rand.Reader) }

// inventFrom — Invent на заданном источнике случайных байт (в тесте — подставной).
func inventFrom(r io.Reader) (string, error) {
	w, err := rand.Int(r, big.NewInt(int64(len(words))))
	if err != nil {
		return "", fmt.Errorf("пароль не придуман: %w", err)
	}
	d, err := rand.Int(r, big.NewInt(10000))
	if err != nil {
		return "", fmt.Errorf("пароль не придуман: %w", err)
	}
	return fmt.Sprintf("%s-%04d", words[w.Int64()], d.Int64()), nil
}

// CheckPassword — пароль годен: пустой («без пароля») или 4…64 знака без управляющих и
// форматирующих (невидимых), в корректном UTF-8.
func CheckPassword(p string) error {
	if p == "" {
		return nil
	}
	if !utf8.ValidString(p) {
		return errors.New("пароль содержит неверные знаки")
	}
	n := utf8.RuneCountInString(p)
	switch {
	case n < MinPassword:
		return fmt.Errorf("пароль короче %d знаков", MinPassword)
	case n > MaxPassword:
		return fmt.Errorf("пароль длиннее %d знаков", MaxPassword)
	}
	for _, c := range p {
		if unicode.IsControl(c) || unicode.Is(unicode.Cf, c) || unicode.Is(unicode.Zl, c) || unicode.Is(unicode.Zp, c) {
			return errors.New("в пароле не бывает управляющих и невидимых знаков")
		}
	}
	return nil
}
