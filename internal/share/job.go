package share

import (
	"github.com/IliaSA101/sosninaalbums/internal/export"
	"github.com/IliaSA101/sosninaalbums/internal/render"
)

// Job — снимок альбома для выгрузки по ссылке (146): всё, что службе нужно от проекта, без самого
// проекта. Собирает его App (internal/app/sharejob.go) за один раз, поэтому путь, хэш сцены и
// страницы одного хода всегда от одного состояния альбома (разбор В1). Служба (sharer) по depguard
// не видит ни album, ни model: она работает только с этим значением.
type Job struct {
	Path string // абсолютный путь .salbum — ключ записи о выгрузке; "" — альбом не сохранён
	UID  string // отпечаток проекта этого снимка (T4-9): запись о ссылке действует только с ним
	// Unsealed — печать отпечатка не пути Path (копия шаблона, файл с другого пути): запись пути
	// для снимка чужая, выгрузка выдаст новый отпечаток (Host.Pin, T4-9).
	Unsealed bool
	Block    string // причина, по которой выгрузить нельзя; "" — можно
	Save     bool   // причина — не сохранён: окно даёт «Сохранить…»
	// Refuse — отказ выгрузки не для block окна (пропавшие фото, рамки, сцена не посчитана):
	// Share() отвечает им словами Go (0.32-146-T5-7).
	Refuse string
	Title  string // название по умолчанию: имя файла альбома без расширения
	Pages  int    // страниц книги
	Bytes  int64  // оценка размера страниц
	Scene  string // хэш сцены (SceneHash) этого снимка

	Spreads []render.Spread
	Cover   *export.CoverJob
	Spec    export.WebSpec

	// Questions — вопросы «Да / Нет» до выгрузки (профиль цвета, пустые поля, шрифты, заготовки);
	// считаются лениво: окно состояния их не просит. nil — вопросов нет.
	Questions func() []string
}
